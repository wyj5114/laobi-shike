SKILL_PATH = Path(os.getenv("NOTE_SKILL_PATH", Path(__file__).resolve().parents[2] / "skills" / "note_generation" / "SKILL.md"))


def load_note_skill() -> str:
    """加载视频笔记生成 Skill；文件不存在时保持原有 prompt 行为。"""
    try:
        if SKILL_PATH.exists():
            return SKILL_PATH.read_text(encoding="utf-8").strip()
    except Exception:
        pass
    return ""

